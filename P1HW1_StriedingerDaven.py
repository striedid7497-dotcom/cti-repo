print("-----Calculating Exponents-----\n")
base = int(input("Enter an integer as the base value: "))
exp = int(input("Enter an integer as the exponent: "))
result1 = base ** exp
print(f"\n{base} raised to the power of {exp} is {result1} !!\n")

